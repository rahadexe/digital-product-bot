-- Failed and successful admin logins per client, shared by every web process.
CREATE TABLE IF NOT EXISTS admin_login_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_ip TEXT NOT NULL,
    attempted_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS admin_login_attempts_client ON admin_login_attempts(client_ip, attempted_at);

