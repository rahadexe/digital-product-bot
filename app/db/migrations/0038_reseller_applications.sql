CREATE TABLE IF NOT EXISTS reseller_applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    tg_user_id BIGINT NOT NULL,
    full_name TEXT NOT NULL,
    telegram_handle TEXT NOT NULL,
    phone_number TEXT NOT NULL,
    channel_link TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending',
    admin_notes TEXT NOT NULL DEFAULT '',
    reviewed_by BIGINT,
    reviewed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_reseller_apps_status ON reseller_applications(status);
CREATE INDEX IF NOT EXISTS idx_reseller_apps_tg_user ON reseller_applications(tg_user_id);
CREATE INDEX IF NOT EXISTS idx_reseller_apps_created_at ON reseller_applications(created_at DESC);
