-- Baseline schema. IF NOT EXISTS lets this adopt the database created before versioned migrations.

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tg_user_id BIGINT UNIQUE NOT NULL,
    username TEXT,
    first_name TEXT,
    last_name TEXT,
    balance NUMERIC(18,4) NOT NULL DEFAULT 0,
    total_spent NUMERIC(18,4) NOT NULL DEFAULT 0,
    rank TEXT NOT NULL DEFAULT 'Standard',
    referred_by BIGINT,
    is_banned INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    icon TEXT NOT NULL DEFAULT '📦',
    sort_order INTEGER NOT NULL DEFAULT 0,
    is_active INTEGER NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT REFERENCES categories(id) ON DELETE SET NULL,
    title TEXT NOT NULL,
    description TEXT,
    price NUMERIC(18,4) NOT NULL CHECK (price > 0),
    icon TEXT DEFAULT '⚡',
    duration_label TEXT DEFAULT '',
    sort_order INTEGER NOT NULL DEFAULT 0,
    is_active INTEGER NOT NULL DEFAULT 1,
    supplier_product_id BIGINT,
    supplier_price NUMERIC(18,4) DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS inventory_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT REFERENCES products(id) ON DELETE CASCADE,
    content TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'available',
    order_id BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    sold_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(id),
    tg_user_id BIGINT NOT NULL,
    product_id BIGINT REFERENCES products(id),
    product_title TEXT NOT NULL,
    price NUMERIC(18,4) NOT NULL,
    delivered_item TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'completed',
    referral_user_id BIGINT,
    referral_bonus NUMERIC(18,4) NOT NULL DEFAULT 0,
    delivery_status TEXT NOT NULL DEFAULT 'legacy',
    request_id TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS deposit_methods (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    account_info TEXT NOT NULL,
    instructions TEXT,
    min_deposit NUMERIC(18,4) NOT NULL DEFAULT 1,
    rate_to_currency NUMERIC(18,8) NOT NULL DEFAULT 1,
    is_active INTEGER NOT NULL DEFAULT 1,
    sort_order INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS deposits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(id),
    tg_user_id BIGINT NOT NULL,
    method_id BIGINT REFERENCES deposit_methods(id),
    method_name TEXT NOT NULL,
    amount NUMERIC(18,4) NOT NULL CHECK (amount > 0),
    transaction_id TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending',
    admin_note TEXT,
    -- Historical rows that repeated an earlier transaction ID stay for investigation.
    legacy_duplicate BOOLEAN NOT NULL DEFAULT false,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    reviewed_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS gate_channels (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_username TEXT NOT NULL,
    chat_id TEXT NOT NULL DEFAULT '',
    title TEXT NOT NULL,
    invite_link TEXT NOT NULL,
    is_active INTEGER NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS bot_settings (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action TEXT NOT NULL,
    details TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS revoked_admin_sessions (
    token_hash TEXT PRIMARY KEY,
    expires_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS supplier_purchase_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tg_user_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    request_id TEXT NOT NULL,
    provider_request_id TEXT UNIQUE NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending',
    order_id BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS broadcasts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tg_user_id BIGINT NOT NULL,
    text TEXT NOT NULL,
    order_id BIGINT UNIQUE,
    broadcast_id BIGINT,
    status TEXT NOT NULL DEFAULT 'pending',
    attempts INTEGER NOT NULL DEFAULT 0,
    next_attempt DOUBLE PRECISION NOT NULL DEFAULT 0,
    error TEXT NOT NULL DEFAULT ''
);

CREATE INDEX IF NOT EXISTS idx_users_ref ON users(referred_by);
CREATE INDEX IF NOT EXISTS idx_orders_tg_user ON orders(tg_user_id, status);
CREATE INDEX IF NOT EXISTS idx_inventory_prod_status ON inventory_items(product_id, status, id);
CREATE INDEX IF NOT EXISTS idx_deposits_tg_user ON deposits(tg_user_id, status);
CREATE INDEX IF NOT EXISTS idx_products_cat_active ON products(category_id, is_active);
CREATE INDEX IF NOT EXISTS supplier_attempt_customer ON supplier_purchase_attempts(tg_user_id, product_id, status);
CREATE INDEX IF NOT EXISTS outbox_due ON outbox(status, next_attempt);
CREATE UNIQUE INDEX IF NOT EXISTS order_request_unique ON orders(tg_user_id, request_id) WHERE request_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS deposit_transaction_unique ON deposits(lower(btrim(transaction_id))) WHERE NOT legacy_duplicate;
CREATE UNIQUE INDEX IF NOT EXISTS deposit_one_pending ON deposits(tg_user_id) WHERE status = 'pending';
