CREATE TABLE admin_notification_jobs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 event_key TEXT NOT NULL UNIQUE,
 kind TEXT NOT NULL CHECK(kind IN ('order','deposit')),
 payload JSONB NOT NULL,
 status TEXT NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','processing','done','failed')),
 attempts INTEGER NOT NULL DEFAULT 0,
 next_attempt TIMESTAMPTZ NOT NULL DEFAULT now(),
 lease_token TEXT,
 error TEXT NOT NULL DEFAULT '',
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX admin_notification_jobs_due ON admin_notification_jobs(next_attempt,id) WHERE status IN ('pending','processing');

CREATE TABLE admin_notification_deliveries (
 job_id BIGINT NOT NULL REFERENCES admin_notification_jobs(id) ON DELETE CASCADE,
 chat_id BIGINT NOT NULL,
 event TEXT NOT NULL,
 PRIMARY KEY(job_id,chat_id,event)
);

