CREATE TABLE IF NOT EXISTS reseller_api_keys (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(id) ON DELETE CASCADE,
    tg_user_id BIGINT NOT NULL,
    key_prefix TEXT NOT NULL,
    key_hash TEXT UNIQUE NOT NULL,
    name TEXT NOT NULL DEFAULT 'Default Key',
    is_active INTEGER NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_used_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_reseller_api_keys_hash ON reseller_api_keys(key_hash) WHERE is_active = 1;
CREATE INDEX IF NOT EXISTS idx_reseller_api_keys_user ON reseller_api_keys(tg_user_id);
