-- Automatic deposits through a payment gateway (ZiniPay). One row per attempt; a completed payment
-- links to the approved deposit that credited the wallet, so it can never be credited twice.
CREATE TABLE IF NOT EXISTS payment_invoices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference TEXT NOT NULL UNIQUE,
    provider TEXT NOT NULL CHECK (provider IN ('zinipay')),
    user_id BIGINT REFERENCES users(id),
    tg_user_id BIGINT NOT NULL,
    credit_amount NUMERIC(18,4) NOT NULL CHECK (credit_amount > 0),
    pay_amount NUMERIC(18,2) NOT NULL CHECK (pay_amount > 0),
    rate NUMERIC(18,8) NOT NULL CHECK (rate > 0),
    provider_invoice_id TEXT UNIQUE,
    payment_url TEXT,
    status TEXT NOT NULL DEFAULT 'created' CHECK (status IN ('created', 'pending', 'completed', 'failed', 'expired')),
    provider_transaction_id TEXT,
    payment_method TEXT,
    deposit_id BIGINT UNIQUE REFERENCES deposits(id),
    last_error TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    completed_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS payment_invoices_customer ON payment_invoices(tg_user_id, status, created_at);
CREATE INDEX IF NOT EXISTS payment_invoices_status ON payment_invoices(status, created_at);
CREATE UNIQUE INDEX IF NOT EXISTS payment_invoices_provider_transaction
    ON payment_invoices(provider, provider_transaction_id) WHERE provider_transaction_id IS NOT NULL;
