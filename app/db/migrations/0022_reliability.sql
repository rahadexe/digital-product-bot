-- The ledger records the exact NUMERIC delta of every balance mutation, including
-- existing code paths and future admin operations. Opening snapshots are explicit.
CREATE TABLE wallet_ledger (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    tg_user_id BIGINT NOT NULL,
    delta NUMERIC(18,4) NOT NULL,
    balance_before NUMERIC(18,4) NOT NULL,
    balance_after NUMERIC(18,4) NOT NULL,
    reason TEXT NOT NULL,
    transaction_id BIGINT NOT NULL DEFAULT txid_current(),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (balance_after = balance_before + delta)
);
CREATE INDEX wallet_ledger_customer ON wallet_ledger(tg_user_id, id DESC);
INSERT INTO wallet_ledger(user_id,tg_user_id,delta,balance_before,balance_after,reason)
SELECT id,tg_user_id,balance,0,balance,'opening_snapshot' FROM users;
CREATE FUNCTION record_wallet_change() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        INSERT INTO wallet_ledger(user_id,tg_user_id,delta,balance_before,balance_after,reason)
        VALUES (NEW.id,NEW.tg_user_id,NEW.balance,0,NEW.balance,'account_opened');
    ELSIF NEW.balance IS DISTINCT FROM OLD.balance THEN
        INSERT INTO wallet_ledger(user_id,tg_user_id,delta,balance_before,balance_after,reason)
        VALUES (NEW.id,NEW.tg_user_id,NEW.balance-OLD.balance,OLD.balance,NEW.balance,
                COALESCE(NULLIF(current_setting('app.wallet_reason',true),''),'balance_update'));
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER wallet_change AFTER INSERT OR UPDATE OF balance ON users
FOR EACH ROW EXECUTE FUNCTION record_wallet_change();
CREATE FUNCTION protect_wallet_ledger() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'Wallet ledger entries are immutable';
END $$;
CREATE TRIGGER wallet_ledger_immutable BEFORE UPDATE OR DELETE ON wallet_ledger
FOR EACH ROW EXECUTE FUNCTION protect_wallet_ledger();

