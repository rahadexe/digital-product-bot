-- All supported writes serialize on the owning product before deduplicating.
-- This also protects direct imports without indexing long credential plaintext.
CREATE FUNCTION prevent_duplicate_stock() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    PERFORM id FROM products WHERE id=NEW.product_id FOR UPDATE;
    IF EXISTS (SELECT 1 FROM inventory_items WHERE product_id=NEW.product_id
               AND content=NEW.content AND id<>NEW.id) THEN
        RAISE unique_violation USING MESSAGE='This product already contains that stock item';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER stock_deduplication BEFORE INSERT OR UPDATE OF product_id, content ON inventory_items
FOR EACH ROW EXECUTE FUNCTION prevent_duplicate_stock();

