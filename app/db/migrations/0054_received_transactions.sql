CREATE TABLE IF NOT EXISTS received_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id TEXT NOT NULL,
    amount NUMERIC(18,4) NOT NULL CHECK (amount > 0),
    provider TEXT NOT NULL DEFAULT 'bKash',
    sender_number TEXT NOT NULL DEFAULT '',
    raw_message TEXT NOT NULL DEFAULT '',
    status TEXT NOT NULL DEFAULT 'unused', -- 'unused', 'used'
    used_by_tg_id BIGINT,
    used_at TIMESTAMPTZ,
    deposit_id BIGINT REFERENCES deposits(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_received_transactions_txid_unique
    ON received_transactions (lower(btrim(transaction_id)));

CREATE INDEX IF NOT EXISTS idx_received_transactions_status
    ON received_transactions (status);
