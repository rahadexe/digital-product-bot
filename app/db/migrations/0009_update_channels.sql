-- Channels shown under the 📢 Channel menu, one link button each. Replaces the single update_channel setting.
CREATE TABLE IF NOT EXISTS update_channels (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    url TEXT NOT NULL,
    sort_order INTEGER NOT NULL DEFAULT 0,
    is_active INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Carry over the old single channel. A bare numeric chat ID has no public link, so it is left out.
INSERT INTO update_channels (title, url)
SELECT 'Updates Channel',
       CASE
           WHEN value LIKE 'http://%' OR value LIKE 'https://%' THEN value
           WHEN value LIKE 't.me/%' THEN 'https://' || value
           ELSE 'https://t.me/' || ltrim(value, '@')
       END
FROM bot_settings
WHERE key = 'update_channel' AND btrim(value) <> '' AND btrim(value) !~ '^-?[0-9]+$';

DELETE FROM bot_settings WHERE key = 'update_channel';
